// Generates design-token files from tokens/figma-export.json (an export of the
// "Personal Design System" Figma file's variables, text styles and effect styles).
//
//   tokens/figma-export.json  ->  src/styles/tokens.css   (CSS custom properties + .type-* classes)
//                             ->  tokens/tokens.json      (W3C Design Tokens format)
//
// Figma is the source of truth: re-export, replace figma-export.json, then run `npm run tokens`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const src = JSON.parse(readFileSync('tokens/figma-export.json', 'utf8'));
const { primitive, semantic } = src.collections;
const MODES = ['Light', 'Dark'];

const FONT_FALLBACKS = {
  Newsreader: 'Georgia, serif',
  'IBM Plex Sans': 'system-ui, sans-serif',
  'IBM Plex Mono': 'ui-monospace, monospace',
};
const WEIGHTS = { Light: 300, Regular: 400, Medium: 500 };

const cssName = (v) => v.css.replace(/^var\(|\)$/g, '');
const allVars = { ...primitive.variables, ...semantic.variables };

// Resolve a value to a literal for a mode, following aliases.
function resolve(name, mode) {
  const value = allVars[name].values[mode];
  return value && typeof value === 'object' ? resolve(value.alias, mode) : value;
}

function cssValue(v, mode) {
  const value = v.values[mode];
  if (value && typeof value === 'object') return `var(${cssName(allVars[value.alias])})`;
  if (v.type === 'FLOAT') return v.unitless ? String(value) : `${value}px`;
  if (v.type === 'STRING') return FONT_FALLBACKS[value] ? `"${value}", ${FONT_FALLBACKS[value]}` : `"${value}"`;
  return value;
}

const rgbChannels = (hex) =>
  [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(' ');

function declarations(mode, { onlyChanged = false } = {}) {
  const lines = [];
  for (const [label, collection] of [['Primitives', primitive], ['Semantic', semantic]]) {
    const block = [];
    for (const [name, v] of Object.entries(collection.variables)) {
      const value = cssValue(v, mode);
      if (onlyChanged && value === cssValue(v, 'Light')) continue;
      block.push(`  ${cssName(v)}: ${value};`);
    }
    if (block.length) lines.push(`  /* ${label} */`, ...block);
  }
  // Space-separated RGB channels for semantic colors, so Tailwind opacity modifiers
  // (e.g. bg-ink/90) work: rgb(var(--text-primary-rgb) / 0.9)
  const rgb = [];
  for (const [name, v] of Object.entries(semantic.variables)) {
    if (v.type !== 'COLOR') continue;
    const value = rgbChannels(resolve(name, mode));
    if (onlyChanged && value === rgbChannels(resolve(name, 'Light'))) continue;
    rgb.push(`  ${cssName(v)}-rgb: ${value};`);
  }
  if (rgb.length) lines.push('  /* Semantic colors as RGB channels */', ...rgb);
  return lines.join('\n');
}

const shadow = (effects) =>
  effects.map((e) => `${e.x}px ${e.y}px ${e.blur}px ${e.spread}px ${e.color}`).join(', ');

const familyVar = (family) =>
  ({ Newsreader: 'serif', 'IBM Plex Sans': 'sans', 'IBM Plex Mono': 'mono' })[family];

function typeClass(style) {
  const name = style.name.replace(/^text\//, '').replace(/\//g, '-');
  const italic = style.fontStyle.includes('Italic');
  const weight = WEIGHTS[style.fontStyle.replace(' Italic', '')] ?? 400;
  const props = [
    `font-family: var(--font-family-${familyVar(style.fontFamily)});`,
    `font-size: ${style.fontSize}px;`,
    `font-weight: ${weight};`,
    italic && 'font-style: italic;',
    `line-height: ${style.lineHeight === 'normal' ? 'normal' : `${style.lineHeight}px`};`,
    style.letterSpacingPercent && `letter-spacing: ${+(style.letterSpacingPercent / 100).toFixed(4)}em;`,
    style.textCase === 'UPPER' && 'text-transform: uppercase;',
  ].filter(Boolean);
  return `.type-${name} {\n  ${props.join('\n  ')}\n}`;
}

const css = `/* Generated by scripts/build-tokens.mjs from tokens/figma-export.json — do not edit by hand.
 * Source: ${src.source.file} (${src.source.url}), exported ${src.source.exported}.
 */

:root {
${declarations('Light')}
  /* Effects */
${src.effectStyles.map((s) => `  --shadow-${s.name.replace(/^elevation\//, '')}: ${shadow(s.effects)};`).join('\n')}
}

/* Dark mode (opt-in): add data-theme="dark" to <html>. */
[data-theme='dark'] {
${declarations('Dark', { onlyChanged: true })}
}

/* Text styles — one class per Figma text style (e.g. text/h1 -> .type-h1). */
${src.textStyles.map(typeClass).join('\n\n')}
`;

// W3C Design Tokens (DTCG) format, with aliases kept as references.
function toDtcg(collection, mode) {
  const out = {};
  for (const [name, v] of Object.entries(collection.variables)) {
    const value = v.values[mode];
    let node = out;
    const parts = name.split('/');
    for (const part of parts.slice(0, -1)) {
      node[part] ??= {};
      if (node[part].$value !== undefined) node[part] = { $self: node[part] };
      node = node[part];
    }
    const leaf = parts.at(-1);
    const type = v.type === 'COLOR' ? 'color' : v.type === 'STRING' ? 'fontFamily' : v.unitless ? 'number' : 'dimension';
    const token = {
      $type: type,
      $value: value && typeof value === 'object' ? `{${value.alias.replace(/\//g, '.')}}` : type === 'dimension' ? `${value}px` : value,
    };
    if (node[leaf] && typeof node[leaf] === 'object') node[leaf].$self = token;
    else node[leaf] = token;
  }
  return out;
}

const dtcg = {
  $description: `Generated from ${src.source.file}, exported ${src.source.exported}. Do not edit by hand.`,
  light: { ...toDtcg(primitive, 'Light'), ...toDtcg(semantic, 'Light') },
  dark: { ...toDtcg(primitive, 'Dark'), ...toDtcg(semantic, 'Dark') },
  typography: Object.fromEntries(
    src.textStyles.map((s) => [
      s.name.replace(/^text\//, '').replace(/\//g, '.'),
      {
        $type: 'typography',
        $value: {
          fontFamily: `{font.family.${familyVar(s.fontFamily)}}`,
          fontWeight: WEIGHTS[s.fontStyle.replace(' Italic', '')] ?? 400,
          fontStyle: s.fontStyle.includes('Italic') ? 'italic' : 'normal',
          fontSize: `${s.fontSize}px`,
          lineHeight: s.lineHeight === 'normal' ? 'normal' : `${s.lineHeight}px`,
          letterSpacing: `${+(s.letterSpacingPercent / 100).toFixed(4)}em`,
          textTransform: s.textCase === 'UPPER' ? 'uppercase' : 'none',
        },
      },
    ]),
  ),
  shadow: Object.fromEntries(
    src.effectStyles.map((s) => [
      s.name.replace(/^elevation\//, ''),
      {
        $type: 'shadow',
        $value: s.effects.map((e) => ({ offsetX: `${e.x}px`, offsetY: `${e.y}px`, blur: `${e.blur}px`, spread: `${e.spread}px`, color: e.color })),
      },
    ]),
  ),
};

mkdirSync('src/styles', { recursive: true });
writeFileSync('src/styles/tokens.css', css);
writeFileSync('tokens/tokens.json', JSON.stringify(dtcg, null, 2) + '\n');
console.log(
  `Wrote src/styles/tokens.css and tokens/tokens.json ` +
    `(${Object.keys(allVars).length} variables, ${src.textStyles.length} text styles, ${src.effectStyles.length} effects)`,
);
